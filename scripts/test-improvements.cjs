// Isolated local API only. Creates a synthetic tenant and uses no external payments.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const base = process.env.LOCALITO_TEST_URL || 'http://127.0.0.1:43100';
const apiBase = process.env.LOCALITO_TEST_API || 'http://127.0.0.1:43101';
for (const url of [base, apiBase]) assert.ok(['127.0.0.1', 'localhost'].includes(new URL(url).hostname));
const out = process.env.LOCALITO_TEST_OUTPUT || path.join(process.cwd(), 'output', 'improvements-qa');
fs.mkdirSync(out, { recursive: true });
(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, serviceWorkers: 'block' });
    const page = await context.newPage(); page.setDefaultTimeout(12000);
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    const email = `qa-full-${Date.now()}@localito.test`, password = 'TestingLocalito2026';
    const registration = await context.request.post(apiBase + '/auth/register', { data: { businessName: 'Negocio de prueba integral', businessType: 'Pruebas', ownerName: 'QA Integral', email, password } });
    assert.equal(registration.ok(), true, await registration.text());
    const auth = (await registration.json()).data;
    const headers = { Authorization: `Bearer ${auth.token}` };
    async function request(route, method = 'get', data) {
      const response = await context.request[method](apiBase + route, { headers, data });
      assert.equal(response.ok(), true, route + ': ' + await response.text());
      return (await response.json()).data;
    }
    const product = await request('/products', 'post', { name: 'Producto foto QA', category: 'Pruebas', salePrice: 1500, costPrice: 500, stock: 30, minimumStock: 5 });
    const customer = await request('/customers', 'post', { name: 'Cliente QA', phone: '912345678', creditLimit: 50000, creditDays: 7 });
    await request('/cash/session/open', 'post', { openingAmount: 10000 });
    await request('/sales', 'post', { paymentMethod: 'credit', customerId: customer.id, items: [{ productId: product.id, quantity: 2 }] });
    await request(`/customers/${customer.id}/payments`, 'post', { amount: 1000, method: 'cash' });
    await request('/cash/movements', 'post', { type: 'expense', amount: 500, reason: 'Gasto de prueba' });
    await page.goto(base);
    await page.getByLabel('Correo', { exact: true }).fill(email);
    await page.getByLabel('Contraseña', { exact: true }).fill(password);
    await page.getByRole('button', { name: 'Iniciar sesión', exact: true }).click();
    await page.locator('.desktop-sidebar').waitFor();
    const button = name => page.getByRole('button', { name, exact: true });
    const nav = name => page.locator('.desktop-sidebar').getByRole('button', { name, exact: true }).click();
    const shot = async name => {
      for (const theme of ['light', 'dark']) {
        await page.evaluate(theme => document.documentElement.dataset.theme = theme, theme);
        await page.waitForTimeout(120);
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, name + ' overflow');
        await page.screenshot({ path: path.join(out, `${name}-${theme}.png`) });
      }
    };
    await page.getByRole('button', { name: 'Configuración', exact: true }).first().click();
    const prefs = page.getByRole('form', { name: 'Cobros y reposición' });
    await prefs.getByLabel('Webpay', { exact: true }).uncheck();
    await prefs.getByLabel('Mercado Pago', { exact: true }).uncheck();
    await prefs.getByRole('button', { name: 'Subir Tarjeta', exact: true }).click();
    await prefs.getByLabel('Banco', { exact: true }).fill('Banco de prueba');
    await prefs.getByLabel('Titular', { exact: true }).fill('Local QA');
    await prefs.getByLabel('Número de cuenta', { exact: true }).fill('12345678');
    await prefs.getByRole('button', { name: 'Guardar cobros y reposición' }).click();
    await page.getByText('Configuración guardada.', { exact: true }).waitFor();
    await shot('settings');
    const workspace = await request('/bootstrap');
    assert.deepEqual(workspace.tenant.preferences.paymentMethods.slice(0, 2), ['card', 'cash']);
    await page.reload(); await page.locator('.desktop-sidebar').waitFor();
    await nav('Vender'); await page.locator('.sale-product-entry .product-button').first().click();
    await page.getByRole('button', { name: /^Cobrar \$/ }).click();
    assert.equal(await page.getByRole('group', { name: 'Medios de pago', exact: true }).getByRole('button').first().innerText(), 'Tarjeta');
    assert.equal(await button('Más').count(), 0);
    await button('Transferencia').click(); await page.getByText('Banco de prueba', { exact: true }).waitFor();
    await shot('bank-checkout');
    await button('Volver al ticket').click();
    await page.locator('.sale-session-tools').getByRole('button', { name: 'Dejar en espera', exact: true }).click();
    await nav('Inventario');
    await page.getByRole('button', { name: 'Editar Producto foto QA', exact: true }).click();
    const image = await page.evaluate(() => { const canvas = document.createElement('canvas'); canvas.width = 100; canvas.height = 100; const ctx = canvas.getContext('2d'); ctx.fillStyle = '#14715f'; ctx.fillRect(30, 10, 40, 80); return canvas.toDataURL('image/png').split(',')[1]; });
    await page.locator('.product-photo-editor input[type=file]').first().setInputFiles({ name: 'photo.png', mimeType: 'image/png', buffer: Buffer.from(image, 'base64') });
    await page.getByRole('slider', { name: 'Escala', exact: true }).fill('1.2');
    await button('Usar foto').click();
    await page.getByRole('form', { name: 'Datos del producto' }).getByRole('button', { name: 'Guardar producto', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('.app-snackbar')?.textContent.includes('Producto actualizado'));
    const saved = (await request('/bootstrap')).products.find(item => item.id === product.id);
    assert.match(saved.imageUrl, /^data:image\/webp;base64,/);
    await nav('Inventario'); await shot('photo-inventory');
    assert.equal(await page.locator('.inventory-compact-row img').first().evaluate(image => image.complete && image.naturalWidth > 0), true);
    await nav('Clientes');
    await page.getByLabel('Cliente del estado de cuenta', { exact: true }).selectOption(customer.id);
    await page.getByLabel('Recordatorio para revisar', { exact: true }).waitFor().catch(async error => { console.log(await page.locator('.customer-statement').innerText()); await page.screenshot({ path: path.join(out, 'statement-failure.png') }); throw error; });
    assert.match(await page.locator('.customer-statement').innerText(), /2\.000/);
    await page.getByLabel('Recordatorio para revisar', { exact: true }).fill('Recordatorio QA revisado');
    assert.match(await page.getByRole('link', { name: 'Abrir WhatsApp', exact: true }).getAttribute('href'), /text=Recordatorio%20QA%20revisado/);
    await page.locator('.customer-statement').scrollIntoViewIfNeeded(); await shot('statement');
    await nav('Caja');
    await page.getByRole('form', { name: 'Conciliar turno' }).waitFor();
    await page.getByLabel('Efectivo contado', { exact: true }).fill('10000');
    assert.equal(await button('Cerrar y conciliar').isDisabled(), true);
    await page.getByLabel('Motivo de la diferencia / nota', { exact: true }).fill('Diferencia QA revisada');
    assert.equal(await button('Cerrar y conciliar').isEnabled(), true);
    assert.match(await page.locator('.cash-breakdown').innerText(), /Abonos de fiado en efectivo.*1\.000/s);
    await page.getByRole('form', { name: 'Conciliar turno' }).scrollIntoViewIfNeeded(); await shot('cash-reconciliation');
    await page.getByRole('heading', { name: 'Historial de cambios', exact: true }).scrollIntoViewIfNeeded();
    await page.getByLabel('Buscar usuario o producto', { exact: true }).fill('Producto foto QA');
    await page.locator('.audit-event summary').first().click();
    assert.match(await page.locator('.audit-event').first().innerText(), /Antes.*Después/s);
    await shot('audit');
    await page.getByRole('heading', { name: 'Reposición por ventas', exact: true }).scrollIntoViewIfNeeded();
    await button('Sin ventas en 30 días').click();
    await shot('replenishment');
    await nav('Vender');
    await page.locator('.sale-product-entry .product-button').first().click();
    await page.getByRole('button', { name: /^Cobrar \$/ }).click();
    await button('Efectivo').click(); await button('Monto exacto').click();
    await page.route('**/sales', route => route.request().method() === 'POST' ? route.abort('internetdisconnected') : route.continue());
    await button('Confirmar cobro').click();
    await button('1 venta pendiente').waitFor();
    const beforeCount = (await request('/bootstrap')).sales.length;
    await button('1 venta pendiente').click(); await shot('sync-error');
    await page.route('**/bootstrap', route => route.abort('internetdisconnected'));
    await page.reload(); await page.locator('.desktop-sidebar').waitFor();
    await nav('Vender');
    assert.equal(await page.locator('.sale-product-entry').count(), 1);
    await button('1 venta pendiente').click();
    await page.unroute('**/bootstrap');
    await page.unroute('**/sales');
    await button('Reintentar').click();
    await button('Sin pendientes').waitFor();
    assert.equal((await request('/bootstrap')).sales.length, beforeCount + 1);
    // A second account must never read or send the first account's queued sales.
    const isolation = await page.evaluate(async () => {
      const module = await import('/src/lib/offline.ts');
      const originalSession = localStorage.getItem('localito-session');
      const originalToken = localStorage.getItem('localito-token');
      const scope = module.syncScope();
      await module.enqueueSale(scope, JSON.stringify({ idempotencyKey: 'isolation-qa', paymentMethod: 'cash', items: [{ productId: 'synthetic-qa', quantity: 1 }] }));
      localStorage.setItem('localito-session', JSON.stringify({ tenant: { id: 'other' }, user: { id: 'other' } }));
      localStorage.setItem('localito-token', 'other-token');
      let sent = 0;
      await module.syncQueue(async () => { sent++; });
      const visible = module.queueEntries().length;
      localStorage.setItem('localito-session', originalSession); localStorage.setItem('localito-token', originalToken);
      const preserved = module.queueEntries().length;
      await Promise.all([module.syncQueue(async () => { sent++; }), module.syncQueue(async () => { sent++; })]);
      return { visible, preserved, sent };
    });
    assert.deepEqual(isolation, { visible: 0, preserved: 1, sent: 1 });
    await page.setViewportSize({ width: 390, height: 950 });
    await shot('mobile-sync');
    await page.setViewportSize({ width: 1440, height: 1000 });
    await nav('Clientes'); await page.getByLabel('Cliente del estado de cuenta', { exact: true }).selectOption(customer.id);
    await page.getByLabel('Recordatorio para revisar', { exact: true }).waitFor();
    await page.setViewportSize({ width: 320, height: 950 }); await page.locator('.customer-statement').scrollIntoViewIfNeeded(); await shot('mobile-statement');
    // Seller API permissions and cross-tenant statement access.
    const seller = await request('/users', 'post', { name: 'QA Seller', email: `seller-${Date.now()}@localito.test`, role: 'seller', password });
    const login = await context.request.post(apiBase + '/auth/login', { data: { email: seller.email, password } });
    const sellerToken = (await login.json()).data.token;
    const denied = await context.request.patch(apiBase + '/tenant/preferences', { headers: { Authorization: `Bearer ${sellerToken}` }, data: workspace.tenant.preferences });
    assert.equal(denied.status(), 403);
    const missing = await context.request.get(apiBase + '/customers/cust-ana/statement', { headers });
    assert.equal(missing.status(), 404);
    assert.deepEqual(errors, []);
    console.log('PASS: persisted payment settings/order/bank, real photo upload, customer statement and reviewed reminder, reconciliation validation, audit details, replenishment, offline retry/isolation/concurrency, seller restrictions and 20 responsive/theme screenshots. Synthetic local tenant only.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
